#!/usr/bin/env python3
"""Generate src/registry.rs from RFC 9669 Appendix A (Table 18).

Table 18 is the normative initial content of the IANA BPF Instruction Set
registry: one row per instruction, with the opcode, the permitted src_reg,
offset, and imm values, and the conformance groups. The proofs use it as the
admission specification, so it is parsed from the checked-in RFC text rather
than transcribed by hand.

Usage: python3 tools/ebpf-formal/gen_registry.py [--check]
"""

import hashlib
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
RFC = ROOT / "docs/specifications/ebpf/rfc9669.txt"
RFC_SHA256 = "54f2d19798d73937befd63ebf7fa65f1a2f1d4a5be29404fb641ca73bb8a1469"
OUTPUT = Path(__file__).resolve().parent / "src/registry.rs"
GROUPS = ["base32", "base64", "atomic32", "atomic64", "divmul32", "divmul64", "packet"]


def rows(text):
    """Yield the cells of every Table 18 row, joining continuation lines.

    Columns are fixed-width (descriptions can contain '|'), so cells are cut
    at the '+' positions of the table's header rule.
    """
    start = text.index("Initial values for the BPF Instruction Set registry are given below.")
    end = text.index("Table 18: Initial BPF Instruction Set Values", start)
    lines = [
        line for line in text[start:end].splitlines()
        if not line.startswith(("Thaler", "RFC 9669")) and "\f" not in line
    ]
    rule = next(line for line in lines if line.strip().startswith("+===="))
    bounds = [index for index, char in enumerate(rule) if char == "+"]
    if len(bounds) != 8:
        raise SystemExit(f"unexpected header rule: {rule!r}")
    current = None
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("+"):
            if current is not None:
                yield current
                current = None
            continue
        if not stripped.startswith("|"):
            continue
        if any(line[bound] != "|" for bound in bounds):
            raise SystemExit(f"row does not match the column rule: {line!r}")
        cells = [line[a + 1:b].strip() for a, b in zip(bounds, bounds[1:])]
        if re.fullmatch(r"0x[0-9a-f]{2}", cells[0]):
            if current is not None:
                raise SystemExit(f"row without separator before {line!r}")
            current = cells
        elif current is not None:
            current = [
                (old + " " + new).strip() if new else old for old, new in zip(current, cells)
            ]
    if current is not None:
        yield current


def selector(cell, name):
    if cell == "any":
        return "Sel::Any"
    if re.fullmatch(r"0x[0-9a-f]+|[0-9]+", cell):
        return f"Sel::Exact({int(cell, 0):#x})"
    raise SystemExit(f"unexpected {name} value {cell!r}")


def main():
    data = RFC.read_bytes()
    if hashlib.sha256(data).hexdigest() != RFC_SHA256:
        raise SystemExit("rfc9669.txt checksum mismatch")
    entries = []
    for opcode, src, offset, imm, description, groups, reference in rows(data.decode()):
        group_names = groups.split()
        if len(group_names) != 1 or group_names[0] not in GROUPS:
            raise SystemExit(f"unexpected groups {groups!r} for {opcode}")
        entries.append((
            int(opcode, 16), selector(src, "src_reg"), selector(offset, "offset"),
            selector(imm, "imm"), group_names[0], " ".join(description.split()),
            " ".join(reference.split()),
        ))
    lines = [
        "//! RFC 9669 Appendix A, Table 18: the initial BPF Instruction Set registry.",
        "//!",
        "//! Generated by `python3 tools/ebpf-formal/gen_registry.py` from",
        f"//! `docs/specifications/ebpf/rfc9669.txt` (SHA-256 `{RFC_SHA256}`).",
        "//! Do not edit by hand.",
        "",
        "use crate::spec::{Entry, Group, Sel};",
        "",
        f"/// The {len(entries)} registered instructions, in table order.",
        "pub const REGISTRY: &[Entry] = &[",
    ]
    for opcode, src, offset, imm, group, description, reference in entries:
        description = description.replace("\\", "\\\\").replace('"', '\\"')
        lines += [
            "    Entry {",
            f"        opcode: {opcode:#04x},",
            f"        src: {src},",
            f"        offset: {offset},",
            f"        imm: {imm},",
            f"        group: Group::{group.capitalize()},",
            f"        description: \"{description}\",",
            f"        reference: \"{reference}\",",
            "    },",
        ]
    lines += ["];", ""]
    output = "\n".join(lines)
    if "--check" in sys.argv:
        if OUTPUT.read_text() != output:
            raise SystemExit("src/registry.rs is stale; rerun gen_registry.py")
        print(f"registry.rs matches Table 18 ({len(entries)} entries)")
        return
    OUTPUT.write_text(output)
    print(f"wrote {OUTPUT} ({len(entries)} entries)")


if __name__ == "__main__":
    main()
