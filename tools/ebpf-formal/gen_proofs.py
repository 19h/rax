#!/usr/bin/env python3
"""Generate the Kani harness tables: src/proofs/opcodes.rs (RFC 9669, one
harness per opcode byte, byte order, and plane) and src/sbpf/opcodes.rs
(Solana SBPF, one harness per version and opcode byte).
Usage: python3 tools/ebpf-formal/gen_proofs.py [--check]"""

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent
RFC_OUTPUT = ROOT / "src/proofs/opcodes.rs"
SBPF_OUTPUT = ROOT / "src/sbpf/opcodes.rs"
PLANES = [
    ("direct", "super::check_direct({opcode:#04x}, Order::{order})"),
    ("smir_o0", "super::smir::check_smir({opcode:#04x}, Order::{order}, &[OptLevel::O0])"),
    ("smir_o1", "super::smir::check_smir({opcode:#04x}, Order::{order}, &[OptLevel::O1])"),
    ("smir_o2", "super::smir::check_smir({opcode:#04x}, Order::{order}, &[OptLevel::O2])"),
]
ORDERS = [("le", "Little"), ("be", "Big")]
VERSIONS = ["V0", "V1", "V2", "V3", "V4"]
HEADER = "//! Generated by `python3 tools/ebpf-formal/gen_proofs.py`. Do not edit."
# The direct plane's division and remainder primitives, engine and
# specification, become one functionally consistent uninterpreted operator
# (src/proofs/operators.rs documents why).
OPERATORS = ["udiv32", "urem32", "udiv64", "urem64", "sdiv32", "srem32", "sdiv64", "srem64"]
def stub(original, replacement):
    """A stub attribute laid out as rustfmt lays it out (100 columns)."""
    line = f"#[kani::stub({original}, {replacement})]"
    if len(line) <= 100:
        return [line]
    return ["#[kani::stub(", f"    {original},", f"    {replacement}", ")]"]


DIRECT_STUBS = [
    line
    for name in OPERATORS
    for owner in ["rax::isa::ebpf::arith", "crate::spec::ops"]
    for line in stub(f"{owner}::{name}", f"crate::proofs::operators::{name}")
]
# Model reduction for SMIR harnesses; src/proofs/smir.rs documents why each
# stub preserves the eBPF semantics.
SMIR_STUBS = [
    "#[kani::stub(",
    "    rax::smir::interpret::exec_rv_vector,",
    "    crate::proofs::smir::no_rv_vector",
    ")]",
    "#[kani::stub(",
    "    rax::smir::interpret::SmirInterpreter::execute_op_x86_stack_flags,",
    "    rax::smir::interpret::SmirInterpreter::execute_op_flags",
    ")]",
    "#[kani::stub(",
    "    rax::smir::interpret::SmirInterpreter::execute_op_opmask,",
    "    crate::proofs::smir::no_category",
    ")]",
    "#[kani::stub(",
    "    rax::smir::interpret::SmirInterpreter::execute_op_far_return,",
    "    crate::proofs::smir::no_category",
    ")]",
]


# SBPF instructions whose reference result is a divider or a high-half
# multiplier, which bit-level SAT cannot equate with the engine's (README):
# DIV/MOD where PQR is disabled, and the V2 PQR divide, remainder, and
# high-multiply forms.
CLASSIC_DIVIDERS = [0x34, 0x3C, 0x37, 0x3F, 0x94, 0x9C, 0x97, 0x9F]
PQR_DIVIDERS = [
    0x36, 0x3E, 0xB6, 0xBE,
    0x46, 0x4E, 0x56, 0x5E, 0x66, 0x6E, 0x76, 0x7E,
    0xC6, 0xCE, 0xD6, 0xDE, 0xE6, 0xEE, 0xF6, 0xFE,
]


def sbpf_step_name(version, opcode):
    dividers = PQR_DIVIDERS if version == "V2" else CLASSIC_DIVIDERS
    family = "divider" if opcode in dividers else "step"
    return f"sbpf_{family}_{version.lower()}_{opcode:02x}"


def rfc_table():
    lines = [
        "//! One harness per opcode byte, byte order, and plane.",
        "//!",
        HEADER,
        "",
        "use rax::smir::optimize::OptLevel;",
        "",
        "use crate::spec::Order;",
        "",
    ]
    for opcode in range(256):
        for order_name, order in ORDERS:
            for plane, call in PLANES:
                lines += [
                    "#[kani::proof]",
                    "#[kani::stub(std::hash::RandomState::new, super::fixed_random_state)]",
                    *(SMIR_STUBS if plane.startswith("smir") else DIRECT_STUBS),
                    "#[kani::unwind(170)]",
                    f"fn {plane}_{order_name}_{opcode:02x}() {{",
                    "    " + call.format(opcode=opcode, order=order) + ";",
                    "}",
                    "",
                ]
    return "\n".join(lines)


def sbpf_table():
    lines = [
        "//! Per SBPF version and opcode byte: admission against the reference",
        "//! verifier, the direct CPU against the reference interpreter, and SMIR at",
        "//! every level against the CPU.",
        "//!",
        HEADER,
        "",
        "use rax::isa::ebpf::SbpfVersion;",
        "use rax::smir::optimize::OptLevel;",
        "",
        "const LEVELS: [OptLevel; 3] = [OptLevel::O0, OptLevel::O1, OptLevel::O2];",
        "",
    ]
    for version in VERSIONS:
        for opcode in range(256):
            lines += [
                "#[kani::proof]",
                "#[kani::stub(rand::thread_rng, super::zeroed_thread_rng)]",
                "#[kani::unwind(17)]",
                f"fn sbpf_admission_{version.lower()}_{opcode:02x}() {{",
                f"    super::check_admission(SbpfVersion::{version}, {opcode:#04x});",
                "}",
                "",
                "#[kani::proof]",
                "#[kani::stub(std::hash::RandomState::new, crate::proofs::fixed_random_state)]",
                "#[kani::stub(rand::thread_rng, super::zeroed_thread_rng)]",
                *stub("solana_sbpf::elf::Executable::get_text_bytes", "super::static_text_bytes"),
                "#[kani::unwind(17)]",
                f"fn {sbpf_step_name(version, opcode)}() {{",
                f"    super::check(SbpfVersion::{version}, {opcode:#04x});",
                "}",
                "",
                "#[kani::proof]",
                "#[kani::stub(std::hash::RandomState::new, crate::proofs::fixed_random_state)]",
                *SMIR_STUBS,
                "#[kani::unwind(17)]",
                f"fn sbpf_smir_{version.lower()}_{opcode:02x}() {{",
                f"    super::smir::check_smir(SbpfVersion::{version}, {opcode:#04x}, &LEVELS);",
                "}",
                "",
            ]
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv
    for output, text in [(RFC_OUTPUT, rfc_table()), (SBPF_OUTPUT, sbpf_table())]:
        name = output.relative_to(ROOT)
        if check:
            if not output.exists() or output.read_text() != text:
                raise SystemExit(f"{name} is stale; rerun gen_proofs.py")
            continue
        output.write_text(text)
        print(f"wrote {name}")


if __name__ == "__main__":
    main()
