//! Architectural trap terminators.

use crate::smir::ir::types::{GuestAddr, MemWidth, OpWidth};

/// Direction selected by an x86 string port-I/O opcode.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum X86StringIoKind {
    /// `INSB`/`INSW`/`INSD`: port `DX` to `ES:(E)DI`/`RDI`.
    Ins,
    /// `OUTSB`/`OUTSW`/`OUTSD`: `DS:(E)SI`/`RSI` to port `DX`.
    Outs,
}

/// Effective memory segment encoded for an x86 string port-I/O operation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum X86Segment {
    Es,
    Cs,
    Ss,
    Ds,
    Fs,
    Gs,
}

/// Trap kinds represented as terminal SMIR control flow.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TrapKind {
    /// Debug breakpoint.
    Breakpoint,
    /// x86 trap-class debug exception generated by `INT1`/`ICEBP` (`F1`).
    ///
    /// `fault_pc` identifies the instruction for an APX-disabled REX2 encoding;
    /// `return_pc` is the post-instruction RIP saved by a successful #DB.
    X86Debug {
        fault_pc: GuestAddr,
        return_pc: GuestAddr,
        requires_apx: bool,
    },
    /// x86 breakpoint exception generated by `INT3` (`CC`).
    ///
    /// This remains distinct from `INT imm8` vector 3 because virtual-8086
    /// IOPL/VME handling and FRED event typing differ. `fault_pc` identifies
    /// the instruction for delivery faults or an APX-disabled REX2 encoding;
    /// `return_pc` is the post-instruction RIP saved by a successful #BP.
    X86Breakpoint {
        fault_pc: GuestAddr,
        return_pc: GuestAddr,
        requires_apx: bool,
    },
    /// x86 software interrupt generated by `INT imm8` (`CD ib`).
    ///
    /// `fault_pc` identifies the instruction for an APX-disabled REX2 encoding;
    /// `return_pc` is the post-instruction RIP saved after successful gate
    /// delivery. Gate lookup, DPL validation, and architectural frame creation
    /// remain an interpreter/runtime boundary.
    X86SoftwareInterrupt {
        vector: u8,
        fault_pc: GuestAddr,
        return_pc: GuestAddr,
        requires_apx: bool,
    },
    /// x86 interrupt return generated by `IRET`/`IRETD`/`IRETQ` (`CF`).
    ///
    /// Stack reads, descriptor validation, privilege transitions, flag
    /// restoration, NMI unblocking, and the control transfer remain an
    /// interpreter/runtime boundary. `fault_pc` is the exact instruction
    /// frontier at which that architecture-specific work must begin.
    X86InterruptReturn {
        width: OpWidth,
        fault_pc: GuestAddr,
        requires_apx: bool,
    },
    /// x86 string port I/O generated by `INS*`/`OUTS*` (`6C`--`6F`).
    ///
    /// Port access, I/O-permission checks, memory faults, REP partial progress,
    /// index/count updates, and the externally visible I/O exit remain an
    /// architecture-integration boundary. SMIR commits no state before this
    /// handoff. `return_pc` is the eventual fallthrough after a successful
    /// non-repeated operation or the final successful REP iteration.
    X86StringIo {
        kind: X86StringIoKind,
        width: MemWidth,
        address_width: OpWidth,
        repeated: bool,
        memory_segment: X86Segment,
        fault_pc: GuestAddr,
        return_pc: GuestAddr,
        requires_apx: bool,
    },
    /// Undefined instruction.
    Undefined,
    /// Division by zero.
    DivideByZero,
    /// Integer overflow.
    Overflow,
    /// Bounds-check failure.
    Bounds,
    /// Invalid opcode.
    InvalidOpcode,
    /// System call.
    SystemCall,
    /// Halt and wait for interrupt.
    Halt,
    /// x86 general-protection exception with architectural error code zero.
    GeneralProtection,
}
